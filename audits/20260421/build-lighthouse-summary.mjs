#!/usr/bin/env node
// Build audits/20260421/lighthouse-mobile/summary.md
// Matrix: page × (Perf/A11y/BP/SEO/LCP/CLS/TBT/tap-targets violations)

import fs from 'node:fs';

const DIR = './audits/20260421/lighthouse-mobile';
const slugToUrl = {
  'home': 'https://aoyama-nogizaka.com/',
  'team': 'https://aoyama-nogizaka.com/team',
  'news': 'https://aoyama-nogizaka.com/news/',
  'privacy': 'https://aoyama-nogizaka.com/privacy',
  'activist-dashboard': 'https://aoyama-nogizaka.com/activist-dashboard.html',
  'risk-assessment': 'https://aoyama-nogizaka.com/risk-assessment.html',
  'activist-screener': 'https://aoyama-nogizaka.com/activist-screener.html',
  'food-service': 'https://aoyama-nogizaka.com/food-service.html',
  'saas': 'https://aoyama-nogizaka.com/saas.html',
  'ad-agency': 'https://aoyama-nogizaka.com/ad-agency.html',
  'digital-media': 'https://aoyama-nogizaka.com/digital-media.html',
  'entertainment-sector-dashboard': 'https://aoyama-nogizaka.com/entertainment-sector-dashboard.html',
  'news-activist-shareholder-proposals-japan': 'https://aoyama-nogizaka.com/news/activist-shareholder-proposals-japan.html',
};
const SLUG_ORDER = Object.keys(slugToUrl);

function markScore(s) {
  if (s === '-' || s == null) return '-';
  if (s < 50) return `**<span style="color:#c00">${s} (poor)</span>**`;
  if (s < 90) return `**<span style="color:#c80">${s} (NI)</span>**`;
  return `${s}`;
}

function parseLCP(s) {
  if (!s) return null;
  const m = /([\d.]+)\s*s/.exec(s);
  return m ? parseFloat(m[1]) : null;
}
function markLCP(s) {
  const n = parseLCP(s);
  if (n == null) return s || '-';
  if (n > 4.0) return `**<span style="color:#c00">${s}</span>**`;
  if (n > 2.5) return `**<span style="color:#c80">${s}</span>**`;
  return s;
}
function markCLS(s) {
  const n = s && !isNaN(parseFloat(s)) ? parseFloat(s) : null;
  if (n == null) return s || '-';
  if (n > 0.25) return `**<span style="color:#c00">${s}</span>**`;
  if (n > 0.1) return `**<span style="color:#c80">${s}</span>**`;
  return s;
}
function parseMS(s) {
  if (!s) return null;
  const m = /([\d,]+)\s*ms/.exec(s);
  return m ? parseInt(m[1].replace(/,/g,''),10) : null;
}
function markTBT(s) {
  const n = parseMS(s);
  if (n == null) return s || '-';
  if (n > 600) return `**<span style="color:#c00">${s}</span>**`;
  if (n > 200) return `**<span style="color:#c80">${s}</span>**`;
  return s;
}

const rows = [];
for (const slug of SLUG_ORDER) {
  const file = `${DIR}/${slug}.json`;
  const url = slugToUrl[slug];
  if (!fs.existsSync(file)) {
    rows.push({ slug, url, perf:'-', a11y:'-', bp:'-', seo:'-', lcp:'-', cls:'-', tbt:'-', tap:'-' });
    continue;
  }
  try {
    const j = JSON.parse(fs.readFileSync(file));
    const c = j.categories || {};
    const a = j.audits || {};
    const sc = k => c[k] && c[k].score != null ? Math.round(c[k].score*100) : '-';
    const v = k => a[k] && a[k].displayValue ? a[k].displayValue : '-';
    // tap-targets is often removed in Lighthouse v13; check both
    let tapCount = '-';
    const tap = a['tap-targets'];
    if (tap) {
      if (tap.details && Array.isArray(tap.details.items)) tapCount = tap.details.items.length;
      else if (tap.score === 1) tapCount = 0;
      else if (tap.score === 0) tapCount = '?';
    } else {
      tapCount = 'N/A';
    }
    rows.push({
      slug, url,
      perf: sc('performance'),
      a11y: sc('accessibility'),
      bp: sc('best-practices'),
      seo: sc('seo'),
      lcp: v('largest-contentful-paint'),
      cls: v('cumulative-layout-shift'),
      tbt: v('total-blocking-time'),
      tap: tapCount,
    });
  } catch (e) {
    rows.push({ slug, url, perf:'-', a11y:'-', bp:'-', seo:'-', lcp:'-', cls:'-', tbt:'-', tap:`parse-err: ${e.message}` });
  }
}

let md = `# Lighthouse Mobile Baseline — 2026-04-21

Form factor: mobile / Chrome headless / Lighthouse CLI v13 系
Generated by: \`audits/20260421/build-lighthouse-summary.mjs\`

## Matrix (page × Perf/A11y/BP/SEO + Core Web Vitals + tap-targets)

色マーク: **赤** = poor / **オレンジ** = needs improvement / 無印 = good

| URL | Perf | A11y | BP | SEO | LCP | CLS | TBT | tap-targets violations |
|---|---:|---:|---:|---:|---:|---:|---:|---:|
`;
for (const r of rows) {
  md += `| [${r.slug}](${r.url}) | ${markScore(r.perf)} | ${markScore(r.a11y)} | ${markScore(r.bp)} | ${markScore(r.seo)} | ${markLCP(r.lcp)} | ${markCLS(r.cls)} | ${markTBT(r.tbt)} | ${r.tap} |\n`;
}

const nums = key => rows.map(r => typeof r[key]==='number'?r[key]:null).filter(x=>x!=null);
const avg = arr => arr.length ? Math.round(arr.reduce((a,b)=>a+b,0)/arr.length*10)/10 : '-';
const perfs = nums('perf'), a11ys = nums('a11y'), bps = nums('bp'), seos = nums('seo');

md += `\n## Aggregates\n\n`;
md += `| Category | avg | min | max | <90 count |\n|---|---:|---:|---:|---:|\n`;
md += `| Performance | ${avg(perfs)} | ${Math.min(...perfs)} | ${Math.max(...perfs)} | ${perfs.filter(x=>x<90).length}/${perfs.length} |\n`;
md += `| Accessibility | ${avg(a11ys)} | ${Math.min(...a11ys)} | ${Math.max(...a11ys)} | ${a11ys.filter(x=>x<90).length}/${a11ys.length} |\n`;
md += `| Best Practices | ${avg(bps)} | ${Math.min(...bps)} | ${Math.max(...bps)} | ${bps.filter(x=>x<90).length}/${bps.length} |\n`;
md += `| SEO | ${avg(seos)} | ${Math.min(...seos)} | ${Math.max(...seos)} | ${seos.filter(x=>x<90).length}/${seos.length} |\n`;

md += `\n## Notes

- Lighthouse v13 系では \`tap-targets\` audit が JSON の \`audits\` キーから除外されているケースがあり、その場合 "N/A" と表示される。
- Windows の Chrome temp-dir cleanup 由来の EPERM が rc=1 として \`_run.log\` に記録されているが、レポート本体 (JSON) は全 13 書き出し済み。
- Thresholds:
  - Score: <50 poor / 50-89 NI / ≥90 good
  - LCP: ≤2.5s good / ≤4.0s NI / >4.0s poor
  - CLS: ≤0.1 good / ≤0.25 NI / >0.25 poor
  - TBT: ≤200ms good / ≤600ms NI / >600ms poor

Raw JSON: \`audits/20260421/lighthouse-mobile/<slug>.json\` (13 files)
Log: \`audits/20260421/lighthouse-mobile/_run.log\`
`;

fs.writeFileSync(`${DIR}/summary.md`, md);
console.log('wrote', `${DIR}/summary.md`);
