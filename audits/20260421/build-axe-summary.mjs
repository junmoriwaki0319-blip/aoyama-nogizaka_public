#!/usr/bin/env node
// Build audits/20260421/axe/summary.md
// Matrix: violation category × page × count

import fs from 'node:fs';

const DIR = './audits/20260421/axe';
const slugToUrl = {
  'home': 'https://aoyama-nogizaka.com/',
  'team': 'https://aoyama-nogizaka.com/team',
  'news': 'https://aoyama-nogizaka.com/news/',
  'privacy': 'https://aoyama-nogizaka.com/privacy',
  'activist-dashboard': 'https://aoyama-nogizaka.com/activist-dashboard.html',
  'risk-assessment': 'https://aoyama-nogizaka.com/risk-assessment.html',
  'activist-screener': 'https://aoyama-nogizaka.com/activist-screener.html',
  'food-service': 'https://aoyama-nogizaka.com/food-service.html',
  'saas': 'https://aoyama-nogizaka.com/saas.html',
  'ad-agency': 'https://aoyama-nogizaka.com/ad-agency.html',
  'digital-media': 'https://aoyama-nogizaka.com/digital-media.html',
  'entertainment-sector-dashboard': 'https://aoyama-nogizaka.com/entertainment-sector-dashboard.html',
  'news-activist-shareholder-proposals-japan': 'https://aoyama-nogizaka.com/news/activist-shareholder-proposals-japan.html',
};
const SLUG_ORDER = Object.keys(slugToUrl);

// Load all
const perPage = {};           // slug -> {category -> count}
const perCategory = {};       // category -> {slug -> count}
const categoriesSet = new Set();
const impactByCategory = {};  // category -> impact (worst of critical/serious/moderate/minor)

for (const slug of SLUG_ORDER) {
  const file = `${DIR}/${slug}.json`;
  perPage[slug] = {};
  if (!fs.existsSync(file)) continue;
  try {
    const j = JSON.parse(fs.readFileSync(file));
    const report = Array.isArray(j) ? j[0] : j;
    const violations = (report && report.violations) || [];
    for (const v of violations) {
      const cat = v.id;
      const nodeCount = (v.nodes || []).length;
      if (nodeCount === 0) continue;
      categoriesSet.add(cat);
      perPage[slug][cat] = (perPage[slug][cat] || 0) + nodeCount;
      if (!perCategory[cat]) perCategory[cat] = {};
      perCategory[cat][slug] = (perCategory[cat][slug] || 0) + nodeCount;
      if (!impactByCategory[cat]) impactByCategory[cat] = v.impact || '';
    }
  } catch (e) {
    console.error('parse fail', slug, e.message);
  }
}

const categories = [...categoriesSet].sort((a,b) => {
  const sumA = Object.values(perCategory[a]||{}).reduce((x,y)=>x+y,0);
  const sumB = Object.values(perCategory[b]||{}).reduce((x,y)=>x+y,0);
  return sumB - sumA;
});

let md = `# axe-core Violations Matrix — 2026-04-21

Source: @axe-core/cli 4.11 (headless chrome)
Generated by: \`audits/20260421/build-axe-summary.mjs\`

## Category × Page (件数)

"-" = 違反なし / 数値 = 該当カテゴリの node 数

| category | impact | ${SLUG_ORDER.join(' | ')} | total |
|---|---|${SLUG_ORDER.map(()=>'---:').join('|')}|---:|
`;

let grandTotal = 0;
const pageTotals = {};
for (const cat of categories) {
  const row = [cat, impactByCategory[cat] || '-'];
  let rowSum = 0;
  for (const slug of SLUG_ORDER) {
    const n = (perCategory[cat] && perCategory[cat][slug]) || 0;
    row.push(n === 0 ? '-' : String(n));
    rowSum += n;
    pageTotals[slug] = (pageTotals[slug] || 0) + n;
  }
  row.push(String(rowSum));
  grandTotal += rowSum;
  md += `| ${row.join(' | ')} |\n`;
}

md += `| **TOTAL** | — | ${SLUG_ORDER.map(s => String(pageTotals[s]||0)).join(' | ')} | **${grandTotal}** |\n`;

md += `\n## Per-page totals\n\n| slug | total |\n|---|---:|\n`;
for (const slug of SLUG_ORDER) {
  md += `| [${slug}](${slugToUrl[slug]}) | ${pageTotals[slug] || 0} |\n`;
}
md += `| **GRAND TOTAL** | **${grandTotal}** |\n`;

md += `\n## Per-category totals\n\n| category | impact | total |\n|---|---|---:|\n`;
for (const cat of categories) {
  const sum = Object.values(perCategory[cat]||{}).reduce((a,b)=>a+b,0);
  md += `| ${cat} | ${impactByCategory[cat] || '-'} | ${sum} |\n`;
}

md += `\n## Notes

- axe-core CLI 4.11 は headless Chrome で各URLに対してアクセスし、WCAG 2.1 / 2.2 AA 相当のルールを実行。
- 同一ルールで複数の node (セレクタ) が該当する場合は各 node を 1 件としてカウント。
- Raw JSON: \`audits/20260421/axe/<slug>.json\` (13 files)
- Log: \`audits/20260421/axe/_run.log\`
`;

fs.writeFileSync(`${DIR}/summary.md`, md);
console.log('wrote', `${DIR}/summary.md`);
console.log('grand total', grandTotal);
console.log('categories', categories.length);
